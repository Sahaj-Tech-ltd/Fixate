/**
 * Fixate Reading Report PDF Generator
 * Client-side jsPDF report. No server needed. Works offline (CDN fallback).
 */
function generateReadingReport({ title, author, date, wpm, wordsRead, timeMinutes, highlights, comprehensionScore, adhdProfile }) {
    const { jsPDF } = window.jspdf;
    if (!jsPDF) {
        alert('PDF generator not loaded. Please check your internet connection.');
        return;
    }

    const doc = new jsPDF({ unit: 'mm', format: 'a4' });
    const pageW = 190; // usable width
    let y = 20;

    // ── Header ──
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(22);
    doc.setTextColor(124, 58, 237); // purple accent
    doc.text('Fixate Reading Report', 10, y);
    y += 8;

    doc.setFontSize(10);
    doc.setTextColor(100, 100, 100);
    doc.setFont('helvetica', 'normal');
    doc.text(`Generated ${date || new Date().toLocaleDateString()}`, 10, y);
    y += 12;

    // ── Document Info ──
    doc.setDrawColor(124, 58, 237);
    doc.setLineWidth(0.5);
    doc.line(10, y, 200, y);
    y += 8;

    doc.setFontSize(14);
    doc.setTextColor(30, 30, 30);
    doc.setFont('helvetica', 'bold');
    doc.text(title || 'Untitled Document', 10, y);
    y += 6;

    doc.setFontSize(10);
    doc.setTextColor(80, 80, 80);
    doc.setFont('helvetica', 'normal');
    if (author) doc.text(`Author: ${author}`, 10, y);
    y += 10;

    // ── Reading Stats ──
    doc.setFontSize(12);
    doc.setTextColor(30, 30, 30);
    doc.setFont('helvetica', 'bold');
    doc.text('Reading Statistics', 10, y);
    y += 7;

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    const stats = [
        `Words per minute (WPM): ${wpm || '—'}`,
        `Total words read: ${wordsRead?.toLocaleString() || '—'}`,
        `Time spent reading: ${timeMinutes ? timeMinutes + ' minutes' : '—'}`,
        `Comprehension: ${comprehensionScore ? comprehensionScore + '%' : 'not assessed'}`,
    ];
    stats.forEach(s => {
        doc.text(`  •  ${s}`, 12, y);
        y += 5;
    });
    y += 5;

    // ── ADHD Profile ──
    if (adhdProfile && adhdProfile.subtype && adhdProfile.subtype !== 'none') {
        doc.setFontSize(12);
        doc.setTextColor(30, 30, 30);
        doc.setFont('helvetica', 'bold');
        doc.text('ADHD Adaptation Profile', 10, y);
        y += 7;

        doc.setFontSize(10);
        doc.setFont('helvetica', 'normal');
        doc.text(`  •  Subtype: ${adhdProfile.subtype}`, 12, y); y += 5;
        doc.text(`  •  Sensory sensitivity: ${adhdProfile.sensory || 'medium'}`, 12, y); y += 5;
        doc.text(`  •  Font: ${adhdProfile.font || 'Inter'}`, 12, y); y += 5;
        doc.text(`  •  Noise: ${adhdProfile.noise || 'pink noise'}`, 12, y); y += 5;
        y += 5;
    }

    // ── Highlights ──
    if (highlights && highlights.length > 0) {
        // Page break if needed
        if (y > 220) { doc.addPage(); y = 20; }

        doc.setFontSize(12);
        doc.setTextColor(30, 30, 30);
        doc.setFont('helvetica', 'bold');
        doc.text(`Highlights (${highlights.length})`, 10, y);
        y += 7;

        doc.setFontSize(9);
        doc.setFont('helvetica', 'normal');
        highlights.slice(0, 25).forEach((h, i) => {
            if (y > 270) { doc.addPage(); y = 20; }
            const text = h.text || h;
            const color = h.color || '#fbbf24';
            doc.setTextColor(30, 30, 30);
            // Color indicator
            doc.setFillColor(color);
            doc.rect(10, y - 3, 3, 3, 'F');
            // Wrap text
            const lines = doc.splitTextToSize(text, pageW - 8);
            lines.forEach(line => {
                if (y > 270) { doc.addPage(); y = 20; }
                doc.text(line, 16, y);
                y += 4;
            });
            y += 1;
        });
    }

    // ── Disclaimer ──
    if (y > 250) { doc.addPage(); y = 20; }
    y += 5;
    doc.setDrawColor(200, 200, 200);
    doc.line(10, y, 200, y);
    y += 6;

    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.setFont('helvetica', 'italic');
    doc.text('This report was generated by Fixate, an ADHD-friendly reading tool.', 10, y); y += 4;
    doc.text('Fixate is a reading aid, not a clinical diagnostic tool. Share this report with your healthcare provider.', 10, y); y += 4;
    doc.text('fixate.app  •  Research-backed ADHD reading assistance', 10, y);

    // ── Save ──
    const filename = `fixate-report-${(title || 'reading').replace(/[^a-zA-Z0-9]/g, '-').substring(0, 30)}.pdf`;
    doc.save(filename);
}

// Export for module use
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { generateReadingReport };
}
